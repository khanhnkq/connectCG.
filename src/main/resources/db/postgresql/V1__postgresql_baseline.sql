);

CREATE INDEX idx_suggestions_user_expires ON friend_suggestions (user_id, expires_at);
CREATE INDEX idx_suggestions_score ON friend_suggestions (user_id, score DESC);

CREATE TABLE dismissed_suggestions (
    user_id INTEGER NOT NULL,
