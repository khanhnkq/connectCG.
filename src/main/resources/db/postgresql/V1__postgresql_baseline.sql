    CONSTRAINT uk_media_storage_object UNIQUE (storage_provider, storage_bucket, object_key)
);

CREATE INDEX idx_media_uploader_type ON media (uploader_id, type);
CREATE INDEX idx_media_uploader_url ON media (uploader_id, url);

