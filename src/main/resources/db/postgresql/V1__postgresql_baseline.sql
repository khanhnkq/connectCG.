CREATE TABLE groups (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id INTEGER NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    cover_media_id INTEGER,
    privacy VARCHAR(20) NOT NULL DEFAULT 'PUBLIC',
    is_deleted BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_groups_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_groups_cover FOREIGN KEY (cover_media_id) REFERENCES media (id) ON DELETE SET NULL,
    CONSTRAINT chk_groups_privacy CHECK (privacy IN ('PUBLIC', 'PRIVATE'))
);

CREATE TABLE group_members (
    group_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
    status VARCHAR(20) NOT NULL DEFAULT 'ACCEPTED',
    invited_by_id INTEGER,
    violation_count INTEGER DEFAULT 0,
    last_violation_at TIMESTAMPTZ,
    joined_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (group_id, user_id),
    CONSTRAINT fk_group_members_group FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE CASCADE,
    CONSTRAINT fk_group_members_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT chk_group_members_role CHECK (role IN ('MEMBER', 'MODERATOR', 'ADMIN')),
    CONSTRAINT chk_group_members_status CHECK (status IN ('ACCEPTED', 'REQUESTED', 'PENDING', 'BANNED'))
);

CREATE TABLE posts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id INTEGER NOT NULL,
    group_id INTEGER,
    original_post_id INTEGER,
    content TEXT,
    visibility VARCHAR(20) DEFAULT 'PUBLIC',
    status VARCHAR(20) DEFAULT 'APPROVED',
    is_deleted BOOLEAN DEFAULT FALSE,
    comment_count INTEGER DEFAULT 0,
    react_count INTEGER DEFAULT 0,
    share_count INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    ai_score DOUBLE PRECISION DEFAULT 0,
    ai_status VARCHAR(20) DEFAULT 'NOT_CHECKED',
    ai_reason TEXT,
    checked_at TIMESTAMPTZ,
    approved_by_id INTEGER,
    is_pinned BOOLEAN DEFAULT FALSE,
    pinned_at TIMESTAMPTZ,
    CONSTRAINT fk_posts_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_posts_group FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE CASCADE,
    CONSTRAINT fk_posts_original_post FOREIGN KEY (original_post_id) REFERENCES posts (id) ON DELETE SET NULL,
    CONSTRAINT fk_posts_approved_by FOREIGN KEY (approved_by_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_posts_visibility CHECK (visibility IN ('PUBLIC', 'FRIENDS', 'PRIVATE')),
    CONSTRAINT chk_posts_status CHECK (status IN ('APPROVED', 'PENDING', 'REJECTED'))
);

CREATE INDEX idx_posts_created_at ON posts (created_at DESC);
CREATE INDEX idx_posts_status ON posts (status);
CREATE INDEX idx_posts_group_feed ON posts (group_id, status, is_deleted, is_pinned DESC, pinned_at DESC, created_at DESC);
CREATE INDEX idx_posts_personal_feed ON posts (status, is_deleted, created_at DESC) WHERE group_id IS NULL;

CREATE TABLE post_media (
    post_id INTEGER NOT NULL,
    media_id INTEGER NOT NULL,
    display_order INTEGER DEFAULT 0,
    PRIMARY KEY (post_id, media_id),
    CONSTRAINT fk_post_media_post FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_post_media_media FOREIGN KEY (media_id) REFERENCES media (id) ON DELETE CASCADE
);

CREATE TABLE comments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id INTEGER NOT NULL,
    author_id INTEGER NOT NULL,
    parent_id INTEGER,
    content TEXT,
    media_id INTEGER,
    is_deleted BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comments_post FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
