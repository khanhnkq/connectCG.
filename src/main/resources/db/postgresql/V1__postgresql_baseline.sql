    icon VARCHAR(50),
    category VARCHAR(50),
    CONSTRAINT uk_hobbies_code UNIQUE (code)
);

CREATE TABLE user_hobbies (
    user_id INTEGER NOT NULL,
    hobby_id INTEGER NOT NULL,
    PRIMARY KEY (user_id, hobby_id),
